def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def dump_json(data: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def slug(value: str) -> str:
    return re.sub(r"[^0-9A-Za-z_.-]+", "_", value).strip("_")


def unique(items: list[str]) -> list[str]:
    return list(dict.fromkeys(items))


def make_distractor_rules(concept: dict[str, Any]) -> list[dict[str, Any]]:
    result = []
    for index, item in enumerate(concept.get("misconceptions", []), start=1):
        result.append({
            "rule_id": f"{slug(concept['concept_id'])}.misconception.{index}",
            "misconception_id": item["misconception_id"],
            "transformation": item.get("diagnosis_tag", "misconception_transform"),
            "validator": "distractor_validity_check",
        })
    return result


