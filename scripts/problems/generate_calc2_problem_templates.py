def validate_catalog_coverage(catalog: dict[str, Any]) -> list[str]:
    missing = []
    for concept in catalog.get("concepts", []):
        gp = concept.get("generation_profile", {})
        if not gp.get("enabled", False):
            continue
        for problem_type in gp.get("supported_problem_types", []):
            if problem_type not in BLUEPRINTS:
                missing.append(f"{concept['concept_id']}::{problem_type}")
    return missing


def generate_catalog(catalog_path: Path, output_dir: Path) -> list[Path]:
    catalog = load_json(catalog_path)
    missing = validate_catalog_coverage(catalog)
    if missing:
        raise RuntimeError("Missing blueprints:\n  - " + "\n  - ".join(missing))

    unit_dir = output_dir / catalog["unit"]["unit_id"]
    written: list[Path] = []
    manifest: list[dict[str, str]] = []

    for concept in catalog.get("concepts", []):
        gp = concept.get("generation_profile", {})
        if not gp.get("enabled", False):
            continue
        for problem_type in gp.get("supported_problem_types", []):
            data = build_template(catalog, concept, problem_type)
            filename = f"{concept['order']:02d}_{slug(concept['concept_id'])}__{slug(problem_type)}.json"
            path = unit_dir / filename
            dump_json(data, path)
            written.append(path)
            manifest.append({
                "template_id": data["template_id"],
                "concept_id": concept["concept_id"],
                "problem_type": problem_type,
                "file": filename,
            })

    dump_json({
        "subject_id": catalog["subject"]["subject_id"],
        "unit_id": catalog["unit"]["unit_id"],
        "template_count": len(written),
        "templates": manifest,
    }, unit_dir / "manifest.json")
    return written


def find_catalog_files(input_path: Path, chapters: list[int] | None) -> list[Path]:
    if input_path.is_file():
        return [input_path]
    if not input_path.is_dir():
        raise FileNotFoundError(input_path)
    files = sorted(input_path.glob("*.json"))
    if chapters:
        selected = []
        for path in files:
            try:
                catalog = load_json(path)
            except Exception:
                continue
            if catalog.get("subject", {}).get("subject_id") == "calculus_2" and catalog.get("unit", {}).get("order") in chapters:
                selected.append(path)
        return selected
    return [p for p in files if load_json(p).get("subject", {}).get("subject_id") == "calculus_2"]


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate ProblemTemplate JSON files for Calculus II concept catalogs.")
    parser.add_argument("input", type=Path, help="One Calculus II catalog JSON or a directory containing catalogs.")
    parser.add_argument("-o", "--output", type=Path, default=Path("data/problem_templates/calculus_2"))
    parser.add_argument("--chapters", nargs="*", type=int, default=None, help="Directory input에서 생성할 unit order. 예: --chapters 1 2 3 4 5 6 7 8")
    args = parser.parse_args()

    catalog_files = find_catalog_files(args.input, args.chapters)
    if not catalog_files:
        raise RuntimeError(f"No Calculus II catalog JSON files found: {args.input}")

    total: list[Path] = []
    for catalog_path in catalog_files:
        written = generate_catalog(catalog_path, args.output)
        total.extend(written)
        print(f"[OK] {catalog_path.name}: {len(written)} templates")

    print()
    print(f"Generated {len(total)} templates in total: {args.output.resolve()}")


if __name__ == "__main__":
    main()
